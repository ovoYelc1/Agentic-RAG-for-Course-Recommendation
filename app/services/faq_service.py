def faq_facts_text() -> str:
    """
    把 FAQ 知识库编译成 system prompt 内联文本。
    每条 answer 本身就是完整的事实句，直接罗列；LLM 读到即可回答政策类问题，
    禁止编造（平台私有事实是幻觉重灾区，必须 grounding 在这份清单上）。
    """
    lines = [f"- {faq['a']}" for faq in FAQ_KB.values()]
    return "\n".join(lines)


def lookup_faq(question: str) -> Optional[str]:
    """
    在知识库中查找匹配的答案，未匹配返回 None（交回 Agent 决定如何处理）。

    匹配策略：
      1. 子串精确包含
      2. 关键词模糊匹配（问题与原问题有 >=2 个相同字）
    """
    return _match_faq_kb(question)


def _match_faq_kb(question: str) -> Optional[str]:
    """匹配内置 FAQ 知识库"""
    q_lower = (question or "").lower().strip()

    for _, faq in FAQ_KB.items():
        # 精确匹配
        for qa in faq["q"]:
            if qa in q_lower or q_lower in qa:
                return faq["a"]

        # 关键词模糊匹配
        for qa in faq["q"]:
            common_words = [w for w in qa if w in q_lower and len(w) >= 2]
            if len(common_words) >= 2:
                return faq["a"]

    return None
